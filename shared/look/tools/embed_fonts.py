#!/usr/bin/env python3
"""Rebuilds shared/look/AskpFonts.cpp from Inter TTFs.

usage: embed_fonts.py Inter-Regular.ttf Inter-Bold.ttf > ../AskpFonts.cpp

The TTFs are a Latin subset of Inter 4.1 (https://github.com/rsms/inter/releases), made with
  pyftsubset Inter-<W>.ttf --layout-features='kern,liga,calt,tnum' --output-file=Inter-<W>.ttf \
    --unicodes="U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2190-2193,U+2212,
                U+00B1,U+2039,U+203A,U+2122,U+00D7,U+2248,U+221E,U+00B0,U+2264,U+2265"
"""
import sys

def arr(name, path):
    b = open(path, 'rb').read()
    rows = ['    ' + ','.join(str(x) for x in b[i:i + 24]) + ',' for i in range(0, len(b), 24)]
    return (f"const unsigned char {name}[] = {{\n" + "\n".join(rows) +
            f"\n}};\nconst int {name}Size = (int) sizeof({name});\n")

print('''// Inter 4.1 by Rasmus Andersson (https://rsms.me/inter), SIL Open Font License 1.1 (see
// look/Inter-LICENSE.txt). Latin subset. Generated by shared/look/tools/embed_fonts.py in the
// askp-dev/hub repo; do not edit.
#ifndef ASKP_LOOK_NS
 #include "../StudioLook.h"   // the product's wrapper, which sets the namespace
#endif

namespace ASKP_LOOK_NS::fonts {''')
print(arr('interRegular', sys.argv[1]) + arr('interBold', sys.argv[2]) + '}', end='\n')
